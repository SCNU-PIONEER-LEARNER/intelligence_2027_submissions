//1. 什么是字节
//字节（Byte）**：计算机基本存储单位，**1 字节 = 8 个比特 (bit)**。
//bit 是 0/1 二进制位；字节是衡量变量占内存多大的单位。
//2. 不同类型的数据的大小相同吗
//不相同，不同 C++ 数据类型占用字节不一样
//3. 计算机的 “内存” 是什么意思
//内存 (RAM，内存条)：**程序运行时临时存放数据的地方**.
//4. 程序正在运行，删掉程序本身文件，会停止运行吗？
//不会立刻停止运行
//5.`auto` 是数据类型吗？
//auto`不是数据类型！
//auto`是类型推导关键字：编译器根据等号右边的值，自动推断出真实的数据类型.   











