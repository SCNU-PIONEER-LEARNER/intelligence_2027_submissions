#include <cstdio>

int main()
{
    int a = 10;
    float b = 3.14f;
    double c = 2.71828;
    char d = 'A';
    const char* str = "PIONEER";

    printf("a = %d\n", a);
    printf("b = %f\n", b);
    printf("c = %lf\n", c);
    printf("d = %c\n", d);
    printf("string:%s\n", str);
    return 0;
}